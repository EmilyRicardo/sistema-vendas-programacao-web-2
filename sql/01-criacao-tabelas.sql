-- Sistema de Vendas | PostgreSQL
-- Execute este arquivo no banco vendas_db ANTES de iniciar a aplicação.
CREATE TABLE IF NOT EXISTS tb_marca (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(120) NOT NULL,
    descricao VARCHAR(500),
    ativo BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE UNIQUE INDEX IF NOT EXISTS uk_tb_marca_nome_lower ON tb_marca (LOWER(nome));

CREATE TABLE IF NOT EXISTS tb_categoria (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(120) NOT NULL,
    categoria_id BIGINT NULL,
    CONSTRAINT fk_categoria_pai FOREIGN KEY (categoria_id) REFERENCES tb_categoria(id) ON DELETE RESTRICT
);
CREATE INDEX IF NOT EXISTS ix_tb_categoria_categoria_id ON tb_categoria(categoria_id);

CREATE TABLE IF NOT EXISTS tb_produto (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(160) NOT NULL,
    descricao TEXT,
    preco NUMERIC(12,2) NOT NULL CHECK (preco > 0),
    quantidade_estoque INTEGER NOT NULL DEFAULT 0 CHECK (quantidade_estoque >= 0),
    marca_id BIGINT NOT NULL,
    categoria_id BIGINT NOT NULL,
    caminho_imagem VARCHAR(255),
    CONSTRAINT fk_produto_marca FOREIGN KEY (marca_id) REFERENCES tb_marca(id) ON DELETE RESTRICT,
    CONSTRAINT fk_produto_categoria FOREIGN KEY (categoria_id) REFERENCES tb_categoria(id) ON DELETE RESTRICT
);
CREATE INDEX IF NOT EXISTS ix_tb_produto_marca_id ON tb_produto(marca_id);
CREATE INDEX IF NOT EXISTS ix_tb_produto_categoria_id ON tb_produto(categoria_id);
CREATE INDEX IF NOT EXISTS ix_tb_produto_nome ON tb_produto(nome);
